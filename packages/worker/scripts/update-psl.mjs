// Regenerates src/psl-data.js from a copy of the Public Suffix List.
//
//   git clone --depth 1 https://github.com/publicsuffix/list.git /tmp/psl
//   node packages/worker/scripts/update-psl.mjs /tmp/psl/public_suffix_list.dat <commit>
//
// Island host names are lowercase ASCII without xn-- labels (protocol
// "地址的写法"), so only such rules are kept.

import { readFileSync, writeFileSync } from 'node:fs';

const [source, commit = 'unknown'] = process.argv.slice(2);
if (!source) throw new Error('usage: update-psl.mjs <public_suffix_list.dat> [commit]');
const rules = readFileSync(source, 'utf8')
  .split('\n')
  .map((line) => line.trim().split(/\s/)[0])
  .filter((rule) => rule && !rule.startsWith('//'))
  .filter((rule) => /^!?(\*\.)?[a-z0-9-]+(\.[a-z0-9-]+)*$/.test(rule) && !/(^|\.)xn--/.test(rule.replace(/^[!*.]+/, '')));
const unique = [...new Set(rules)].sort();
const out = `// Generated by scripts/update-psl.mjs from the Public Suffix List
// (https://publicsuffix.org/, commit ${commit}). Do not edit by hand.
// This file is derived from the Public Suffix List and is available under
// the Mozilla Public License, version 2.0: https://mozilla.org/MPL/2.0/
// ASCII rules only; ${unique.length} rules.

export const SOURCE = ${JSON.stringify(commit)};
export const RULES = ${JSON.stringify(unique.join('\n'))};
`;
writeFileSync(new URL('../src/psl-data.js', import.meta.url), out);
console.log(`${unique.length} rules written`);
